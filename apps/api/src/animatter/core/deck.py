"""Deck planning: turning a transcript into pages, with no IO (§19.6).

What "one page" means
---------------------
Not one sentence. A 583-sentence episode would be 583 pages, and every page would flip
before anyone could read it. A page is a **topic stretch**, and the boundaries are the two
things that actually mark one in spoken audio:

* a **time gap** — the speaker stopped, something changed;
* a **length cap** — a stretch that never pauses still has to break somewhere, or a page
  ends up with 400 characters on it.

**Speaker change is deliberately not a boundary**, even though it looks like one. Measured on
the sample episode, turns alternate 320+ times; splitting there would produce a page every
few seconds and the deck would be unreadable in a different way. A back-and-forth is one
topic, not two — the page's *text* is what shows the dialogue, and the deck is a summary, not
a transcript.

Where the page *starts* is the load-bearing number: it is both the render trigger and the
point the video switches pages, so it is expressed as a **sentence `ord` plus its absolute
millisecond** — the same pair `core/script.py` uses for chapters, and the same reason
`video_item` stores absolute ms (§19.3): every candidate identity for "which sentence" turned
out to be unstable.

Why no LLM here
---------------
Titles generated by a model are nicer, but they make the whole feature depend on a paid call
and on a prompt that can drift. This module produces **structure** deterministically — the
page break points, the source sentence, the raw text — and the editor is where a human makes
it good. That is also what the design promises: 「生成后有一栏逐页校对」.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final

from animatter.core.script import ScriptSentence

#: Longest a page may stay on screen before it is cut regardless of what follows. Measured
#: on the real 61.5-minute episode (17,294 characters, 4.69 chars/s): 60 s lands at ~293
#: characters per page, which sets at 44–48 px in the sample box — about one page per minute,
#: 59 pages for the whole episode.
TARGET_PAGE_MS: Final[int] = 60_000

#: How long a page must already be before a mere pause is worth breaking at. Below this the
#: page is still short enough that cutting it produces a flicker of pages rather than a deck.
#: With this pair the observed page lengths are p10 54 s / p50 63 s / p90 71 s.
SEAM_AFTER_MS: Final[int] = 45_000

#: What counts as a pause worth breaking at, measured on the real episode: sentence gaps are
#: p50 320 ms, p75 520 ms, p90 830 ms. So ~700 ms is roughly "a real beat", which happens a
#: few dozen times an hour — unlike the 1.5 s threshold, which occurred only 12 times.
PAGE_GAP_MS: Final[int] = 700

#: How much text one page carries before it is cut regardless of time. 480 CJK characters
#: sets at 32 px / 13 lines in the sample box, which is the smallest size that still reads at
#: 1080p — below that the auto-shrink is producing a wall of text, not a slide.
MAX_PAGE_CHARS: Final[int] = 480

#: A page shorter than this flashes; it is merged forward instead. Deliberately much smaller
#: than :data:`SEAM_AFTER_MS`: that one decides *where* to break, this one refuses a page that
#: would be gone before it is read.
MIN_PAGE_MS: Final[int] = 8_000

#: How many sentences of the source text to keep as the page's context in the editor. The
#: body is trimmed to MAX_PAGE_CHARS; the full stretch is kept for the proofreading pane.
CONTEXT_CHARS: Final[int] = 900

#: Title length cap, same convention as the ShowNotes titles (``MAX_TITLE_CHARS``).
MAX_TITLE_CHARS: Final[int] = 26

#: Where a title may be cut. Ordered by nothing — :func:`_title_from` takes the earliest
#: position of any of them, because the first *clause* is what a reader scans.
_CLAUSE_MARKS: Final[tuple[str, ...]] = ("。", "！", "？", "；", "，")


@dataclass(frozen=True)
class PagePlan:
    """One page before it becomes a row: where it starts and what it says."""

    #: Sentence ord of the first sentence on this page — what the editor jumps to.
    source_ord: int
    #: Absolute start on the **original** timeline. The video block maps it through the EDL.
    start_ms: int
    #: Last sentence ord covered, inclusive. Used to build the proofreading context.
    last_ord: int
    title: str
    body: str
    #: The whole stretch's text, for the editor's left pane. Never rendered.
    context: str
    speaker: int | None


def _clean(text: str) -> str:
    """Collapse whitespace so a page's body is one flowing paragraph.

    Newlines in a transcript are an artefact of sentence segmentation, not meaning; keeping
    them would make every page look like a list.
    """
    return " ".join(text.split())


def _title_from(text: str) -> str:
    """A provisional title: the page's first clause, cut to the cap.

    Deliberately the first clause rather than a summary: it is a placeholder the human
    rewrites, and a placeholder that already says what the page is *about* is far easier to
    improve than 「第 7 页」.

    The **earliest** clause mark wins, not the first mark *type*: taking 「。」 first would
    return a whole sentence on every page, which is a title nobody can scan.
    """
    body = _clean(text)
    cut = min(
        (index for mark in _CLAUSE_MARKS if 4 <= (index := body.find(mark)) <= MAX_TITLE_CHARS),
        default=-1,
    )
    if cut >= 0:
        return body[:cut]
    return body[:MAX_TITLE_CHARS] if len(body) > MAX_TITLE_CHARS else body


def plan_pages(
    sentences: list[ScriptSentence],
    *,
    max_page_chars: int = MAX_PAGE_CHARS,
    gap_ms: int = PAGE_GAP_MS,
    min_page_ms: int = MIN_PAGE_MS,
    target_page_ms: int = TARGET_PAGE_MS,
    seam_after_ms: int = SEAM_AFTER_MS,
) -> list[PagePlan]:
    """Group sentences into pages.

    Grouping runs over **sentences**, not turns: turns merge consecutive same-speaker
    sentences and would hide the pause between two of them, which is exactly the boundary
    this needs to see.

    Two thresholds, not one, and that is the whole design. A page ends when it has **run
    long enough** (:data:`TARGET_PAGE_MS`) *or* when it has run long enough to be worth
    breaking **and** a pause follows (:data:`SEAM_AFTER_MS` + :data:`PAGE_GAP_MS`). A plain
    "break at any pause" rule produced 238 pages on a 61-minute episode — one every 15
    seconds, which is a slideshow, not a deck.

    Returns at least one page whenever there is any text, and an empty list for an empty
    transcript — "no pages" is a real state (an unprocessed project) that the caller reports,
    not an error.
    """
    usable = [item for item in sentences if item.text.strip()]
    if not usable:
        return []

    groups: list[list[ScriptSentence]] = []
    current: list[ScriptSentence] = []
    for item in usable:
        if current and _should_break(
            current,
            item,
            max_page_chars=max_page_chars,
            gap_ms=gap_ms,
            target_page_ms=target_page_ms,
            seam_after_ms=seam_after_ms,
        ):
            groups.append(current)
            current = []
        current.append(item)
    if current:
        groups.append(current)

    # A page too short to read is merged into the previous one. Doing this after grouping
    # (rather than preventing the split) keeps `_should_break` a simple, testable predicate.
    merged: list[list[ScriptSentence]] = []
    for group in groups:
        if merged and _span_ms(group) < min_page_ms:
            merged[-1].extend(group)
        else:
            merged.append(group)

    pages: list[PagePlan] = []
    for group in merged:
        text = _clean("".join(item.text for item in group))
        pages.append(
            PagePlan(
                source_ord=group[0].ord,
                start_ms=group[0].start_ms,
                last_ord=group[-1].ord,
                title=_title_from(text),
                body=text[:max_page_chars],
                context=text[:CONTEXT_CHARS],
                speaker=group[0].speaker,
            )
        )
    return pages


def _should_break(
    current: list[ScriptSentence],
    item: ScriptSentence,
    *,
    max_page_chars: int,
    gap_ms: int,
    target_page_ms: int,
    seam_after_ms: int,
) -> bool:
    """Whether ``item`` opens a new page.

    Three reasons, in order of how often they fire on real speech:

    1. the page already holds ``max_page_chars`` — never let one page become a wall;
    2. the page has run past ``target_page_ms`` — the length cap that keeps pages moving;
    3. the page has run past ``seam_after_ms`` **and** a pause follows — break at the natural
       seam rather than at the cap, which is why this check comes last and only applies once
       the page is old enough to be worth ending early.

    The char cap is checked *before* adding, so a page never exceeds it by one sentence; that
    means one long sentence can overflow on its own, which is why ``body`` is also truncated.
    """
    chars = sum(len(entry.text) for entry in current)
    if chars + len(item.text) > max_page_chars:
        return True
    elapsed = current[-1].end_ms - current[0].start_ms
    if elapsed >= target_page_ms:
        return True
    return elapsed >= seam_after_ms and item.start_ms - current[-1].end_ms >= gap_ms


def _span_ms(group: list[ScriptSentence]) -> int:
    return group[-1].end_ms - group[0].start_ms


def page_spans(pages: list[PagePlan], *, total_ms: int) -> list[tuple[PagePlan, int, int]]:
    """Each page's ``(start_ms, end_ms)`` stretch, in original time.

    A page runs until the next one starts; the last one runs to the end of the film. Doing
    it here rather than storing an end on every row means inserting a page does not require
    rewriting its neighbour.
    """
    out: list[tuple[PagePlan, int, int]] = []
    for index, page in enumerate(pages):
        end = pages[index + 1].start_ms if index + 1 < len(pages) else total_ms
        out.append((page, page.start_ms, max(page.start_ms, end)))
    return out
